const defaultRequired = ['VERIFICATION', 'PASSWORD_RESET', 'PASSWORD_CHANGED', 'ACCOUNT_RECOVERY'];

function getRequiredKeys() {
  if (process.env.EMAIL_REQUIRED_TEMPLATES) {
    return process.env.EMAIL_REQUIRED_TEMPLATES.split(',')
      .map((k) => k.trim().toUpperCase())
      .filter(Boolean);
  }
  return defaultRequired;
}

function resolveEnvForKey(key) {
  const names = TEMPLATE_KEYS[key] || [];
  return names.find((name) => process.env[name]);
}

function main() {
  const requiredKeys = getRequiredKeys();
  const missing = requiredKeys.filter((key) => !resolveEnvForKey(key));

  const strict = process.env.EMAIL_STRICT_TEMPLATES === '1' || process.env.CI === 'true';
  const apiKeyMissing = !process.env.SENDGRID_API_KEY;

  if (!strict && !missing.length && !apiKeyMissing) {
    console.log('Email template check passed (non-strict).');
    return;
  }

  if (apiKeyMissing) {
    console.error('SENDGRID_API_KEY is missing.');
  }

  if (missing.length) {
    console.error('Missing required SendGrid templates:', missing.join(', '));
  }

  if (strict && (missing.length || apiKeyMissing)) {
    process.exit(1);
  } else {
    process.exit(0);
  }
}

main();
